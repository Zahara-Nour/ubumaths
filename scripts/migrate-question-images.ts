// Environment variables (only check in execute mode)
const supabaseUrl = process.env.PUBLIC_SUPABASE_URL;
const supabaseServiceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (isExecute && (!supabaseUrl || !supabaseServiceKey)) {
	console.error('❌ Missing required environment variables:');
	console.error('   - PUBLIC_SUPABASE_URL');
	console.error('   - SUPABASE_SERVICE_ROLE_KEY');
	process.exit(1);
}

// ============================================================================
// TYPES
// ============================================================================

interface MigrationResult {
	sourcePath: string;
	targetPath: string;
	originalSize: number;
	convertedSize: number;
	reduction: number; // Percentage
	success: boolean;
	error?: string;
	publicUrl?: string;
}

interface MigrationStats {
	total: number;
	succeeded: number;
	failed: number;
	skipped: number;
	totalOriginalBytes: number;
	totalConvertedBytes: number;
	averageReduction: number;
}

interface UrlMapping {
	[oldPath: string]: string; // oldPath -> new public URL
}

// ============================================================================
// IMAGE DISCOVERY
// ============================================================================

/**
 * Check if a file path matches any exclude pattern
 */
function isExcluded(filePath: string): boolean {
	const normalizedPath = path.normalize(filePath);

	for (const pattern of CONFIG.excludePatterns) {
		// Convert glob pattern to regex
		const regexPattern = pattern.replace(/\*\*/g, '.*').replace(/\*/g, '[^/]*').replace(/\?/g, '.');

		const regex = new RegExp(regexPattern);

		if (regex.test(normalizedPath)) {
			return true;
		}
	}

	return false;
}

/**
 * Find all source images in configured directories
 */
async function findSourceImages(): Promise<string[]> {
	console.log('🔍 Searching for source images...\n');

	const allImages: string[] = [];
	let _totalFound = 0;
	let totalExcluded = 0;

	for (const dir of CONFIG.sourceDirs) {
		const fullPath = path.resolve(dir);

		// Check if directory exists
		try {
			await fs.access(fullPath);
		} catch {
			console.log(`⏭️  Skipping non-existent directory: ${dir}`);
			continue;
		}

		// Find images in this directory
		for (const ext of CONFIG.supportedFormats) {
			const pattern = path.join(fullPath, `**/*.${ext}`);
			const images = await glob(pattern, {
				ignore: CONFIG.excludePatterns
			});

			// Additional filtering with custom exclude logic
			const filtered = images.filter((img) => {
				if (isExcluded(img)) {
					totalExcluded++;
					return false;
				}
				return true;
			});

			allImages.push(...filtered);
			_totalFound += images.length;
		}

		console.log(`   ${dir}: ${allImages.length} images (${totalExcluded} excluded)`);
	}

	// Remove duplicates and sort
	const uniqueImages = [...new Set(allImages)].sort();

	console.log(`\n✅ Found ${uniqueImages.length} unique question image(s)`);
	console.log(`   (Excluded ${totalExcluded} non-question images)\n`);

	return uniqueImages;
}

// ============================================================================
// IMAGE CONVERSION (Dry-run compatible)
// ============================================================================

/**
 * Convert image to WebP format
 * In dry-run mode, only calculates estimated size without sharp
 */
async function convertToWebP(sourcePath: string): Promise<Buffer | null> {
	if (isDryRun) {
		// In dry-run mode, we don't actually convert
		// Just return null to skip conversion
		return null;
	}

	// NOTE: sharp must be installed for execute mode
	// Run: pnpm add -D sharp
	try {
		const sharp = (await import('sharp')).default;

		return await sharp(sourcePath)
			.webp({
				quality: CONFIG.quality,
				effort: CONFIG.effort
			})
			.toBuffer();
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code === 'ERR_MODULE_NOT_FOUND') {
			console.error('\n❌ Error: sharp package not found');
			console.error('   Install with: pnpm add -D sharp\n');
			process.exit(1);
		}
		throw error;
	}
}

// ============================================================================
// SUPABASE UPLOAD
// ============================================================================

/**
 * Delay helper for retry logic
 */
function delay(ms: number): Promise<void> {
	return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Upload image buffer to Supabase Storage with retry logic
 * Returns public URL
 */
async function uploadToSupabase(
	supabase: ReturnType<typeof createClient>,
	buffer: Buffer,
	targetPath: string
): Promise<string> {
	let lastError: Error | null = null;

	for (let attempt = 1; attempt <= CONFIG.maxRetries; attempt++) {
		try {
			// Upload to storage
			const { error: uploadError } = await supabase.storage
				.from(CONFIG.bucket)
				.upload(targetPath, buffer, {
					contentType: 'image/webp',
					cacheControl: '31536000', // 1 year (immutable images)
					upsert: true // Allow re-running script
				});

			if (uploadError) {
				throw new Error(`Upload failed: ${uploadError.message}`);
			}

			// Get public URL
			const {
				data: { publicUrl }
			} = supabase.storage.from(CONFIG.bucket).getPublicUrl(targetPath);

			return publicUrl;
		} catch (error) {
			lastError = error instanceof Error ? error : new Error(String(error));

			if (attempt < CONFIG.maxRetries) {
				const waitTime = CONFIG.retryDelayMs * attempt; // Exponential backoff
				console.log(`   ⚠️  Retry ${attempt}/${CONFIG.maxRetries} in ${waitTime}ms...`);
				await delay(waitTime);
			}
		}
	}

	throw lastError || new Error('Upload failed after retries');
}

// ============================================================================
// MIGRATION LOGIC
// ============================================================================

/**
 * Generate target path for an image
 * Preserves directory structure within source
 */
function generateTargetPath(sourcePath: string): string {
	// Find which source directory this image comes from
	for (const dir of CONFIG.sourceDirs) {
		const fullDir = path.resolve(dir);
		if (sourcePath.startsWith(fullDir)) {
			// Get relative path from source directory
			const relativePath = path.relative(fullDir, sourcePath);

			// Replace extension with .webp
			const targetPath = relativePath.replace(/\.(png|jpg|jpeg)$/i, '.webp');

			return targetPath;
		}
	}

	// Fallback: use basename with webp extension
	const basename = path.basename(sourcePath, path.extname(sourcePath));
	return `${basename}.webp`;
}

/**
 * Migrate a single image
 */
async function migrateImage(
	sourcePath: string,
	supabase: ReturnType<typeof createClient> | null
): Promise<MigrationResult> {
	const targetPath = generateTargetPath(sourcePath);

	try {
		// Get original file stats
		const stats = await fs.stat(sourcePath);
		const originalSize = stats.size;

		// Convert to WebP
		const webpBuffer = await convertToWebP(sourcePath);

		if (isDryRun) {
			// Dry run mode: estimate conversion
			const estimatedSize = Math.round(originalSize * 0.3); // WebP is ~30% of PNG
			const reduction = ((originalSize - estimatedSize) / originalSize) * 100;

			return {
				sourcePath,
				targetPath,
				originalSize,
				convertedSize: estimatedSize,
				reduction,
				success: true
			};
		}

		// Execute mode: actual conversion
		if (!webpBuffer || !supabase) {
			throw new Error('Missing buffer or Supabase client');
		}

		const convertedSize = webpBuffer.length;
		const reduction = ((originalSize - convertedSize) / originalSize) * 100;

		// Upload to Supabase
		const publicUrl = await uploadToSupabase(supabase, webpBuffer, targetPath);

		return {
			sourcePath,
			targetPath,
			originalSize,
			convertedSize,
			reduction,
			success: true,
			publicUrl
		};
	} catch (error) {
		return {
			sourcePath,
			targetPath,
			originalSize: 0,
			convertedSize: 0,
			reduction: 0,
			success: false,
			error: error instanceof Error ? error.message : String(error)
		};
	}
}

// ============================================================================
// BATCH PROCESSING
// ============================================================================

/**
 * Process images in batches
 */
async function processInBatches(
	images: string[],
	supabase: ReturnType<typeof createClient> | null
): Promise<MigrationResult[]> {
	const results: MigrationResult[] = [];
	const batches = Math.ceil(images.length / CONFIG.batchSize);

	console.log(`📦 Processing ${images.length} images in ${batches} batch(es)...\n`);

	for (let i = 0; i < images.length; i += CONFIG.batchSize) {
		const batch = images.slice(i, i + CONFIG.batchSize);
		const batchNumber = Math.floor(i / CONFIG.batchSize) + 1;

		console.log(`\n📦 Batch ${batchNumber}/${batches} (${batch.length} images)`);
		console.log('='.repeat(70));

		// Process batch in parallel
		const batchResults = await Promise.all(
			batch.map(async (imagePath) => {
				const result = await migrateImage(imagePath, supabase);

				// Log individual result
				const status = result.success ? '✅' : '❌';
				const sizeInfo = result.success
					? `${formatBytes(result.originalSize)} → ${formatBytes(result.convertedSize)} (-${result.reduction.toFixed(1)}%)`
					: result.error;

				console.log(`${status} ${path.basename(result.sourcePath)}`);
				console.log(`   ${sizeInfo}`);
				if (result.publicUrl) {
					console.log(`   URL: ${result.publicUrl}`);
				}

				return result;
			})
		);

		results.push(...batchResults);
	}

	return results;
}

