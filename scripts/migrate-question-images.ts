/**
 * Format bytes to human-readable string
 */
function formatBytes(bytes: number): string {
	if (bytes === 0) return '0 B';
	const k = 1024;
	const sizes = ['B', 'KB', 'MB'];
	const i = Math.floor(Math.log(bytes) / Math.log(k));
	return `${(bytes / Math.pow(k, i)).toFixed(2)} ${sizes[i]}`;
}

/**
 * Calculate migration statistics
 */
function calculateStats(results: MigrationResult[]): MigrationStats {
	const succeeded = results.filter((r) => r.success);
	const failed = results.filter((r) => !r.success);

	const totalOriginalBytes = succeeded.reduce((sum, r) => sum + r.originalSize, 0);
	const totalConvertedBytes = succeeded.reduce((sum, r) => sum + r.convertedSize, 0);

	const averageReduction =
		succeeded.length > 0
			? succeeded.reduce((sum, r) => sum + r.reduction, 0) / succeeded.length
			: 0;

	return {
		total: results.length,
		succeeded: succeeded.length,
		failed: failed.length,
		skipped: 0,
		totalOriginalBytes,
		totalConvertedBytes,
		averageReduction
	};
}

/**
 * Print migration summary
 */
function printSummary(stats: MigrationStats, mode: 'dry-run' | 'execute'): void {
	console.log('\n' + '='.repeat(70));
	console.log(`📊 Migration Summary (${mode.toUpperCase()})`);
	console.log('='.repeat(70));
	console.log(`Total images:         ${stats.total}`);
	console.log(`✅ Succeeded:         ${stats.succeeded}`);
	console.log(`❌ Failed:            ${stats.failed}`);
	console.log(`⏭️  Skipped:           ${stats.skipped}`);
	console.log('');
	console.log(`Original size:        ${formatBytes(stats.totalOriginalBytes)}`);
	console.log(`Converted size:       ${formatBytes(stats.totalConvertedBytes)}`);
	console.log(
		`Space saved:          ${formatBytes(stats.totalOriginalBytes - stats.totalConvertedBytes)} (${stats.averageReduction.toFixed(1)}% avg reduction)`
	);
	console.log('='.repeat(70) + '\n');
}

/**
 * Generate URL mapping file
 */
async function generateUrlMapping(results: MigrationResult[]): Promise<void> {
	const mapping: UrlMapping = {};

	for (const result of results) {
		if (result.success && result.publicUrl) {
			// Map old path to new public URL
			mapping[result.sourcePath] = result.publicUrl;

			// Also map relative paths from various base directories
			for (const dir of CONFIG.sourceDirs) {
				const fullDir = path.resolve(dir);
				if (result.sourcePath.startsWith(fullDir)) {
					const relativePath = path.relative(fullDir, result.sourcePath);
					mapping[relativePath] = result.publicUrl;
					mapping[`/${relativePath}`] = result.publicUrl;
					mapping[`/images/${relativePath}`] = result.publicUrl;
				}
			}
		}
	}

	// Write mapping file
	const mappingPath = path.resolve(CONFIG.mappingFile);
	await fs.writeFile(mappingPath, JSON.stringify(mapping, null, 2), 'utf-8');

	console.log(`📝 URL mapping written to: ${CONFIG.mappingFile}`);
	console.log(`   ${Object.keys(mapping).length} mappings generated\n`);
}

// ============================================================================
// MAIN
// ============================================================================

async function main() {
	console.log('🚀 Question Image Migration Script');
	console.log('='.repeat(70));
	console.log(
		`Mode: ${isDryRun ? '🧪 DRY RUN (no actual changes)' : '✍️  EXECUTE (will upload to Supabase)'}\n`
	);

	// 1. Find all source images
	const images = await findSourceImages();

	if (images.length === 0) {
		console.log('✅ No images found to migrate.');
		return;
	}

	// 2. Initialize Supabase client (only in execute mode)
	let supabase: ReturnType<typeof createClient> | null = null;

	if (isExecute) {
		supabase = createClient(supabaseUrl!, supabaseServiceKey!, {
			auth: {
				autoRefreshToken: false,
				persistSession: false
			}
		});

		// Verify bucket exists
		const { data: buckets, error } = await supabase.storage.listBuckets();
		if (error) {
			console.error('❌ Error accessing Supabase Storage:', error.message);
			process.exit(1);
		}

		const bucketExists = buckets?.some((b) => b.name === CONFIG.bucket);
		if (!bucketExists) {
			console.error(`❌ Error: Bucket '${CONFIG.bucket}' does not exist in Supabase Storage`);
			console.error('   Create it in the Supabase Dashboard first.');
			process.exit(1);
		}

		console.log(`✅ Connected to Supabase Storage (bucket: ${CONFIG.bucket})\n`);
	}

	// 3. Process images
	const results = await processInBatches(images, supabase);

	// 4. Calculate and print statistics
	const stats = calculateStats(results);
	printSummary(stats, isDryRun ? 'dry-run' : 'execute');

	// 5. Generate URL mapping (only in execute mode)
	if (isExecute) {
		await generateUrlMapping(results);
	}

	// 6. Final messages
	if (isDryRun) {
		console.log('🧪 DRY RUN COMPLETE - No changes were made');
		console.log('💡 To apply migration, run with --execute flag');
		console.log('   Note: Install sharp first with: pnpm add -D sharp\n');
	} else {
		if (stats.failed > 0) {
			console.log('⚠️  Some images failed to migrate. Review errors above.');
			process.exit(1);
		} else {
			console.log('🎉 Migration completed successfully!');
			console.log('✅ All images converted to WebP and uploaded to Supabase Storage');
			console.log(`📝 URL mapping saved to ${CONFIG.mappingFile}\n`);
		}
	}
}

// ============================================================================
// ENTRY POINT
// ============================================================================

main().catch((error) => {
	console.error('❌ Fatal error:', error);
	process.exit(1);
});
