#!/usr/bin/env tsx
/**
 * Question Image Migration Script
 * ================================
 *
 * Converts PNG question images to WebP format and uploads to Supabase Storage.
 *
 * Context:
 * - 214 unique images referenced in old questions system
 * - All PNG format (100%)
 * - Converting PNG → WebP with quality 85 for ~70% size reduction
 * - Target: Supabase Storage bucket 'question-images'
 *
 * IMPORTANT: Source images are NOT in this repository!
 * You must obtain them first (see README for instructions).
 *
 * Prerequisites:
 *   1. Run: pnpm tsx scripts/extract-question-image-refs.ts
 *      This generates scripts/question-images-list.json
 *   2. Obtain source images (download from production, backup, or generate)
 *   3. Place images in one of the configured source directories
 *   4. Install sharp: pnpm add -D sharp (only needed for --execute)
 *   5. Set env vars: PUBLIC_SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY
 *   6. Create bucket 'question-images' in Supabase Storage
 *
 * Usage:
 *   pnpm tsx scripts/migrate-question-images.ts --dry-run   # Preview
 *   pnpm tsx scripts/migrate-question-images.ts --execute   # Migrate
 *
 * Output:
 *   - Uploads images to Supabase Storage
 *   - Generates mapping file: scripts/image-url-mapping.json
 *
 * @see scripts/README-question-images.md - Full documentation
 * @see scripts/question-images-list.json - List of all referenced images
 * @see docs/wip/question-migration-analysis.md (Section 22) - Analysis
 */

import { createClient } from '@supabase/supabase-js';
import * as dotenv from 'dotenv';
import * as fs from 'fs/promises';
import * as path from 'path';
import { glob } from 'glob';

dotenv.config();

// ============================================================================
// CONFIGURATION
// ============================================================================

