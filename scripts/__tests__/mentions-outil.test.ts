/**
 * Mentions de l'outil dans un message de commit (`scripts/mentions-outil.cjs`) : signature,
 * trailer de session, lien de session. Le mot seul reste permis (`docs(claude): …`, `CLAUDE.md`).
 */

import { describe, it, expect } from 'vitest';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { regleMentionOutil, trouverMentionOutil } = require('../mentions-outil.cjs') as {
	regleMentionOutil: (parsed: { raw?: string }) => [boolean, string];
	trouverMentionOutil: (texte: string) => string | null;
};

const EN_TETE = 'fix(outils): bouton signaler\n\n';
// Adresse de l'éditeur, écrite en deux morceaux : la garde des données sensibles lit ce fichier
const ADRESSE = ['noreply', 'anthropic.com'].join('@');

describe('trouverMentionOutil', () => {
	it('refuse la signature de co-auteur, quelle que soit la casse', () => {
		expect(trouverMentionOutil(EN_TETE + `Co-Authored-By: Claude <${ADRESSE}>`)).toBe(
			'Co-Authored-By'
		);
		expect(trouverMentionOutil(EN_TETE + 'co-authored-by: Claude Fable 5 <a@exemple.test>')).toBe(
			'Co-Authored-By'
		);
	});

	it('refuse le trailer de session et le lien de session', () => {
		expect(trouverMentionOutil(EN_TETE + 'Claude-Session: abc')).toBe('Claude-Session');
		expect(trouverMentionOutil(EN_TETE + 'Voir https://claude.ai/code/session_01')).toBe(
			'lien claude.ai'
		);
	});

	it('refuse la mention « généré avec » et l’adresse de l’éditeur', () => {
		expect(trouverMentionOutil(EN_TETE + '🤖 Generated with [Claude Code](https://ex.test)')).toBe(
			'Generated with'
		);
		expect(trouverMentionOutil(EN_TETE + 'Generated by Claude Code')).toBe('Generated with');
		expect(trouverMentionOutil(EN_TETE + `Signed-off-by: X <${ADRESSE}>`)).toBe(
			'adresse anthropic.com'
		);
	});

	it('laisse passer le mot seul et la signature d’un humain', () => {
		expect(trouverMentionOutil('docs(claude): section gros process resserree')).toBeNull();
		expect(
			trouverMentionOutil(EN_TETE + 'CLAUDE.md et .claude/settings.json mis a jour')
		).toBeNull();
		expect(trouverMentionOutil(EN_TETE + 'le hook Claude refuse la commande')).toBeNull();
		expect(
			trouverMentionOutil(EN_TETE + 'Co-Authored-By: Camille <camille@exemple.test>')
		).toBeNull();
	});
});

describe('regleMentionOutil (commitlint)', () => {
	it('rend un refus qui nomme la mention trouvée', () => {
		const [valide, raison] = regleMentionOutil({ raw: EN_TETE + 'Claude-Session: abc' });
		expect(valide).toBe(false);
		expect(raison).toContain('Claude-Session');
		expect(regleMentionOutil({ raw: 'docs(claude): rien' })[0]).toBe(true);
		expect(regleMentionOutil({})[0]).toBe(true);
	});
});
