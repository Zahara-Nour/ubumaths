# Opérateurs arithmétiques
a, b = 17, 5
print(a + b, a - b, a * b)
print(a / b)    # division : 3.4
print(a // b)   # division entière : 3
print(a % b)    # modulo : 2
print(a ** b)   # puissance : 17^5

# Opérateurs de comparaison
print(a > b, a == b, a != b)

# Opérateurs logiques
x = True
y = False
print(x and y, x or y, not x)

# Affectations composées
n = 10
n += 5    # n = n + 5
n *= 2    # n = n * 2
print("n =", n)
