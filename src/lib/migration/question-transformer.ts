/**
 * Convert old validation options to new format
 *
 * Maps old TinyMath options to new ConstraintOptions structure:
 * - require-* options → constraint: 'strict'
 * - no-penalty-for-* options → constraint: 'off'
 * - Display/generation options → defaultDisplayOptions
 * - Display options (enounce-no-spaces) → silently ignored
 */
function convertOptions(
	oldOptions: string[] | undefined,
	warnings: string[],
	oldFormats?: string[]
): {
	options?: QuestionTemplate['options'];
	defaultDisplayOptions?: DisplayOptions;
	requiredForm?: RequiredForm;
} {
	if (!oldOptions || oldOptions.length === 0) {
		return {};
	}

	const options: QuestionTemplate['options'] = {};
	const constraints: ConstraintOptions = {};
	const displayOptions: DisplayOptions = {};
	let requiredForm: RequiredForm | undefined;
	// Note: mappedCount tracked for potential debugging but not used in return
	let _mappedCount = 0;

	for (const option of oldOptions) {
		switch (option) {
			// ================================================================
			// CONSTRAINT OPTIONS - Spaces
			// ================================================================
			case 'require-correct-spaces':
				constraints.spaces = 'strict';
				_mappedCount++;
				break;
			case 'no-penalty-for-incorrect-spaces':
				constraints.spaces = 'off';
				_mappedCount++;
				break;

			// ================================================================
			// CONSTRAINT OPTIONS - Products
			// ================================================================
			case 'require-implicit-products':
				constraints.products = 'strict';
				_mappedCount++;
				break;
			case 'no-penalty-for-explicit-products':
				constraints.products = 'off';
				_mappedCount++;
				break;

			// ================================================================
			// CONSTRAINT OPTIONS - Brackets
			// ================================================================
			case 'require-no-extraneous-brackets':
				constraints.brackets = 'strict';
				_mappedCount++;
				break;
			case 'no-penalty-for-extraneous-brackets':
				constraints.brackets = 'off';
				_mappedCount++;
				break;
			case 'no-penalty-for-extraneous-brackets-in-first-negative-term':
				constraints.brackets = 'off';
				constraints.allowBracketsInFirstNegativeTerm = true;
				_mappedCount++;
				break;

			// ================================================================
			// CONSTRAINT OPTIONS - Zeros
			// ================================================================
			case 'require-no-extraneous-zeros':
				constraints.zeros = 'strict';
				_mappedCount++;
				break;
			case 'no-penalty-for-extraneous-zeros':
				constraints.zeros = 'off';
				_mappedCount++;
				break;

			// ================================================================
			// CONSTRAINT OPTIONS - Null terms (CE pattern matching)
			// ================================================================
			case 'require-no-null-terms':
				constraints.nullTerms = 'strict';
				_mappedCount++;
				break;
			case 'no-penalty-for-null-terms':
				constraints.nullTerms = 'off';
				_mappedCount++;
				break;

			// ================================================================
			// CONSTRAINT OPTIONS - Factor one (CE pattern matching)
			// ================================================================
			case 'require-no-factor-one':
				constraints.factorOne = 'strict';
				_mappedCount++;
				break;
			case 'no-penalty-for-factor-one':
				constraints.factorOne = 'off';
				_mappedCount++;
				break;

			// ================================================================
			// CONSTRAINT OPTIONS - Factor zero (CE pattern matching)
			// ================================================================
			case 'require-no-factor-zero':
				constraints.factorZero = 'strict';
				_mappedCount++;
				break;
			case 'no-penalty-for-factor-zero':
				constraints.factorZero = 'off';
				_mappedCount++;
				break;

			// ================================================================
			// CONSTRAINT OPTIONS - Signs (CE pattern matching)
			// ================================================================
			case 'require-no-extraneous-signs':
				constraints.signs = 'strict';
				_mappedCount++;
				break;
			case 'no-penalty-for-extraneous-signs':
				constraints.signs = 'off';
				_mappedCount++;
				break;

			// ================================================================
			// FRACTION OPTIONS → constraints.reducedFractions
			// ================================================================
			case 'require-reduced-fractions':
				// Require fractions to be reduced to lowest terms
				constraints.reducedFractions = 'strict';
				_mappedCount++;
				break;
			case 'no-penalty-for-non-reduced-fractions':
				// Don't penalize non-reduced fractions
				constraints.reducedFractions = 'off';
				_mappedCount++;
				break;

			// ================================================================
			// SHUFFLE CHOICES - Implemented
			// ================================================================
			case 'no-shuffle-choices':
				options.shuffleChoices = false;
				_mappedCount++;
				break;

			// ================================================================
			// UNIT CONSTRAINT - Implemented (same pattern as other constraints)
			// ================================================================
			case 'require-specific-unit':
				constraints.unit = 'strict';
				_mappedCount++;
				break;
			case 'no-penalty-for-not-respected-unit':
				constraints.unit = 'off';
				_mappedCount++;
				break;

			// ================================================================
			// NOT IMPLEMENTED - VALIDATION OPTIONS (generate warnings)
			// ================================================================
			case 'solutions-order-not-important':
				if (oldFormats && oldFormats.length > 0) {
					// Question has a formats field (e.g. "$e[2;99]*$e[2;99]")
					// This is a single-answer question with multiple valid solutions.
					// Convert format to requiredForm pattern + use numerical equivalence.
					// The old format "$e[2;99]*$e[2;99]" becomes a product-of-integers pattern.
					requiredForm = { pattern: 'a:inN & gte(2) * b:inN & gte(2)' };
					_mappedCount++;
				} else {
					// Multi-answer question where order doesn't matter
					// (e.g., absolute value equations, polynomial roots)
					options.orderIndependent = true;
					_mappedCount++;
				}
				break;
			case 'disallow-factors-permutation':
				// Redundant with products constraint since the LaTeX parser
				// rejects wrong-order implicit multiplication (e.g. a3, √2·3).
				// The only way to write wrong-order factors is with explicit ×,
				// which products:'strict' already catches.
				if (!constraints.products || constraints.products !== 'strict') {
					constraints.products = 'strict';
				}
				_mappedCount++;
				break;
			case 'penalty-for-factors-permutation':
				// Redundant with products constraint (same reasoning as above).
				// Default products mode is 'warn' which gives partial credit,
				// matching the old penalty behavior.
				_mappedCount++;
				break;
			case 'disallow-terms-permutation':
			case 'disallow-terms-and-factors-permutation':
			case 'penalty-for-terms-permutation':
			case 'penalty-for-terms-and-factors-permutation':
				// No questions use these (0 occurrences) — ignore silently
				_mappedCount++;
				break;
			case 'one-single-form-solution':
				// Requires structural match (strictlyEquals in old system).
				// The solution "0-&1" must be written exactly as 0 minus something.
				requiredForm = { pattern: '0 - a' };
				_mappedCount++;
				break;

			// ================================================================
			// DISPLAY GENERATION OPTIONS → defaultDisplayOptions
			// ================================================================
			case 'shuffle-terms':
				displayOptions.shuffleTerms = true;
				_mappedCount++;
				break;
			case 'shuffle-factors':
				displayOptions.shuffleFactors = true;
				_mappedCount++;
				break;
			case 'shuffle-terms-and-factors':
				displayOptions.shuffleTermsAndFactors = true;
				_mappedCount++;
				break;
			case 'shallow-shuffle-terms':
				displayOptions.shallowShuffleTerms = true;
				_mappedCount++;
				break;
			case 'shallow-shuffle-factors':
				displayOptions.shallowShuffleFactors = true;
				_mappedCount++;
				break;
			case 'remove-null-terms':
				displayOptions.removeNullTerms = true;
				_mappedCount++;
				break;

			// ================================================================
			// NOT IMPLEMENTED - GENERATION OPTIONS (generate warnings)
			// ================================================================
			case 'exhaust':
				// TODO: Generate all possible variations without repetition
				warnings.push(`TODO: ${option} - exhaustive generation not yet implemented`);
				break;

			// ================================================================
			// LATEX FORMATTING OPTIONS → defaultDisplayOptions
			// ================================================================
			case 'exp-no-spaces':
				displayOptions.removeSpaces = true;
				_mappedCount++;
				break;
			case 'exp-remove-unecessary-brackets':
				displayOptions.removeUnnecessaryBrackets = true;
				_mappedCount++;
				break;
			// ================================================================
			// DISPLAY OPTIONS - Silently ignored (cosmetic only)
			// ================================================================
			case 'exp-allow-unecessary-zeros':
			case 'enounce-no-spaces':
				// Display formatting options - cosmetic only, safe to ignore
				_mappedCount++;
				break;

			// ================================================================
			// LEGACY OPTIONS - Silently ignored (not needed)
			// ================================================================
			case 'allow-same-expression':
			case 'allow-same-enounce':
			case 'multiples':
				// Legacy generation uniqueness options - not needed in new system
				_mappedCount++;
				break;

			default:
				warnings.push(`Unknown option: ${option} - needs manual review`);
		}
	}

	// Add constraints to options if any were set
	if (Object.keys(constraints).length > 0) {
		options.constraints = constraints;
	}

	// Build result object
	const hasOptions = Object.keys(options).length > 0;
	const hasDisplayOptions = Object.keys(displayOptions).length > 0;

	return {
		options: hasOptions ? options : undefined,
		defaultDisplayOptions: hasDisplayOptions ? displayOptions : undefined,
		requiredForm
	};
}

