/**
 * Result of shared fields detection
 */
interface SharedFieldsResult {
	/** Shared defaults that apply to all variations */
	shared: SharedVariationDefaults;
	/** Per-variation data that differs between variations */
	perVariation: Partial<QuestionVariation>[];
}

/**
 * Detect which fields are shared across all variations.
 *
 * In TinyMath, an array with 1 element for N variations means the field is shared.
 * For example:
 * - `enounces.length === 1` with `variationCount > 1` → shared statement
 * - `variabless.length === 1` with `variationCount > 1` → shared variables
 * - `solutionss.length === 1` with `variationCount > 1` → shared solution
 * - etc.
 *
 * @param oldQuestion - The old TinyMath question
 * @param variationCount - Number of variations detected
 * @param questionType - The detected question type
 * @param imageMapping - Optional mapping for image URLs
 * @param warnings - Array to collect warnings
 * @param stats - Stats object to track conversions
 * @returns Object containing shared defaults and per-variation data
 */
function detectSharedFields(
	oldQuestion: QuestionBase,
	variationCount: number,
	migrationMode: MigrationMode,
	imageMapping: ImageUrlMapping | undefined,
	warnings: string[],
	stats: TransformStats
): SharedFieldsResult {
	const shared: SharedVariationDefaults = {};
	const perVariation: Partial<QuestionVariation>[] = Array.from(
		{ length: variationCount },
		() => ({})
	);

	// Get images array (shared across all variations in old format)
	const images = oldQuestion.images;

	// ---- Detect enounces sharing (→ statement) ----
	const enounces = oldQuestion.enounces || [];
	const expressions = oldQuestion.expressions || [];
	const answerFields = oldQuestion.answerFields || [];

	// Collect expression variables to add to perVariation later (after regular variables)
	const expressionVariables: (QuestionVariable | undefined)[] = [];

	if (migrationMode === 'answer_field') {
		// AnswerField mode: convert answerField to statement with $?$
		// The answerField replaces the expression in the statement
		const answerFieldIsShared = answerFields.length === 1 && variationCount > 1;
		const enounceIsShared = enounces.length === 1 && variationCount > 1;

		if (answerFieldIsShared && (enounceIsShared || enounces.length === 0)) {
			// Shared answerField
			const enonce = enounces[0];
			const convertedField = convertAnswerFieldToStatement(answerFields[0], warnings);
			const parts: string[] = [];
			if (enonce) {
				const enonceResult = convertTinyCASToNew(enonce);
				parts.push(enonceResult.converted || enonce);
			}
			parts.push(convertedField);
			shared.statement = templateMarkdown(fixMathDelimiters(parts.join('\n\n')));
			for (let i = 0; i < variationCount; i++) {
				perVariation[i].statement = shared.statement;
				expressionVariables.push(undefined); // No expression variable for answerField
			}
		} else {
			// Per-variation answerField
			for (let i = 0; i < variationCount; i++) {
				const enonce = enounces[i] || enounces[0];
				const af = answerFields[i] || answerFields[0];
				const convertedField = convertAnswerFieldToStatement(af, warnings);
				const parts: string[] = [];
				if (enonce) {
					const enonceResult = convertTinyCASToNew(enonce);
					parts.push(enonceResult.converted || enonce);
				}
				parts.push(convertedField);
				perVariation[i].statement = templateMarkdown(fixMathDelimiters(parts.join('\n\n')));
				expressionVariables.push(undefined); // No expression variable for answerField
			}
		}
	} else {
		// Standard mode: enounce + expression → statement
		const enounceIsShared = enounces.length === 1 && variationCount > 1;
		const expressionIsShared =
			(expressions.length === 0 || expressions.length === 1) && variationCount > 1;
		const statementIsShared =
			(enounceIsShared || enounces.length === 0) &&
			(expressionIsShared || expressions.length === 0);

		if (statementIsShared) {
			// Shared enounce AND shared/no expression - generate statement once
			const enonce = enounces[0];
			const expression = expressions[0];
			const result = convertStatement(
				enonce,
				expression,
				1, // Always expression1 when shared
				images,
				imageMapping,
				warnings,
				stats
			);
			shared.statement = result.statement;
			// All variations share the same statement and expression variable
			for (let i = 0; i < variationCount; i++) {
				perVariation[i].statement = result.statement;
				expressionVariables.push(result.expressionVariable);
			}
		} else {
			// Per-variation statements or expressions
			for (let i = 0; i < variationCount; i++) {
				const enonce = enounces[i] || enounces[0];
				const expression = expressions[i] || expressions[0];
				const result = convertStatement(
					enonce,
					expression,
					i + 1, // expressionIndex varies per variation
					images,
					imageMapping,
					warnings,
					stats
				);
				perVariation[i].statement = result.statement;
				expressionVariables.push(result.expressionVariable);
			}
		}
	}

	// ---- Detect variabless sharing (→ variables) ----
	const variabless = oldQuestion.variabless || [];
	const variablesIsShared = variabless.length === 1 && variationCount > 1;

	if (variablesIsShared) {
		const convertedVars = convertVariables(variabless[0], warnings);
		if (convertedVars && convertedVars.length > 0) {
			shared.variables = convertedVars;
			stats.variables += convertedVars.length;
		}
	} else {
		for (let i = 0; i < variationCount; i++) {
			const variables = variabless[i] || variabless[0];
			const convertedVars = convertVariables(variables, warnings);
			if (convertedVars && convertedVars.length > 0) {
				perVariation[i].variables = convertedVars;
				stats.variables += convertedVars.length;
			}
		}
	}

	// ---- Add expression variables AFTER regular variables (for correct resolution order) ----
	for (let i = 0; i < variationCount; i++) {
		const exprVar = expressionVariables[i];
		if (exprVar) {
			if (!perVariation[i].variables) {
				perVariation[i].variables = [];
			}
			perVariation[i].variables!.push(exprVar);
		}
	}

	// ---- Handle expressions2 (creates expression2 variable for QCM with 2 expressions) ----
	const expressions2 = oldQuestion.expressions2 || [];
	if (expressions2.length > 0) {
		for (let i = 0; i < variationCount; i++) {
			const expr2 = expressions2[i] || expressions2[0];
			if (expr2) {
				const conversionResult = convertTinyCASToNew(expr2);
				const afterTinyCAS = conversionResult.converted || expr2;
				const bareExpr = toBareVariableSyntax(toSimplifiedSyntax(afterTinyCAS));

				const expr2Var: QuestionVariable = {
					name: `expression${2}`,
					expression: bareExpr
				};

				if (!perVariation[i].variables) {
					perVariation[i].variables = [];
				}
				perVariation[i].variables!.push(expr2Var);

				// Update statement to also reference expression2
				const currentStatement = String(perVariation[i].statement ?? shared.statement ?? '');
				if (!currentStatement.includes('{{expression2}}')) {
					const updatedStatement = currentStatement + '\n\n$${{expression2}}$$';
					perVariation[i].statement = templateMarkdown(updatedStatement);
				}
			}
		}
	}

	// ---- Detect solutionss sharing (→ solution) ----
	// Only create solution for multiple_choice. For fill_in_blanks modes,
	// blanks[] is the source of truth (created in createVariationsWithShared).
	const solutionss = oldQuestion.solutionss || [];
	const solutionIsShared = solutionss.length === 1 && variationCount > 1;

	if (migrationMode === 'multiple_choice') {
		// MC needs solution (correct answer index/indices)
		if (solutionss.length > 0) {
			if (solutionIsShared) {
				shared.correctChoiceIndex = convertSolution(solutionss[0], 'multiple_choice', warnings);
			} else {
				for (let i = 0; i < variationCount; i++) {
					const solutions = solutionss[i] || solutionss[0];
					perVariation[i].correctChoiceIndex = convertSolution(
						solutions,
						'multiple_choice',
						warnings
					);
				}
			}
		}
	}
	// For non-MC modes: blanks[] will be created in createVariationsWithShared

	// ---- Detect correction sharing (correctionDetailss + correctionFormats) ----
	const correctionDetailss = oldQuestion.correctionDetailss || [];
	const correctionFormats = oldQuestion.correctionFormats || [];
	const hasCorrections = correctionDetailss.length > 0 || correctionFormats.length > 0;

	// Correction is shared if both arrays have 0 or 1 elements for multiple variations
	const detailsIsShared = correctionDetailss.length <= 1 && variationCount > 1;
	const formatsIsShared = correctionFormats.length <= 1 && variationCount > 1;
	const correctionIsShared = detailsIsShared && formatsIsShared;

	if (correctionIsShared && hasCorrections) {
		// Multiple variations, single correction → shared
		const questionCorrection = transformCorrection(
			correctionDetailss[0],
			correctionFormats[0],
			warnings,
			stats
		);
		if (questionCorrection) {
			shared.correction = questionCorrection;
		}
	} else if (correctionDetailss.length > 1 || correctionFormats.length > 1) {
		// Multiple corrections → per-variation
		for (let i = 0; i < variationCount; i++) {
			const correctionDetails = correctionDetailss[i] || correctionDetailss[0];
			const correctionFormat = correctionFormats[i] || correctionFormats[0];
			const questionCorrection = transformCorrection(
				correctionDetails,
				correctionFormat,
				warnings,
				stats
			);
			if (questionCorrection) {
				perVariation[i].correction = questionCorrection;
			}
		}
	} else if (variationCount === 1 && hasCorrections) {
		// Single variation with correction → per-variation[0]
		const questionCorrection = transformCorrection(
			correctionDetailss[0],
			correctionFormats[0],
			warnings,
			stats
		);
		if (questionCorrection) {
			perVariation[0].correction = questionCorrection;
		}
	}

	// ---- Detect choices sharing (for multiple_choice) ----
	const choicess = oldQuestion.choicess || [];
	const choicesIsShared = choicess.length === 1 && variationCount > 1;

	if (migrationMode === 'multiple_choice' && choicess.length > 0) {
		// For QCM, choices don't have isCorrect - the correct choice is determined
		// at runtime by evaluating the solution (which contains the correct index)
		if (choicesIsShared) {
			shared.choices = convertChoices(choicess[0], imageMapping, warnings, stats);
		} else {
			for (let i = 0; i < variationCount; i++) {
				const choices = choicess[i] || choicess[0];
				perVariation[i].choices = convertChoices(choices, imageMapping, warnings, stats);
			}
		}
	}

	// ---- Detect testAnswerss sharing (→ validationRules) ----
	const testAnswerss = oldQuestion.testAnswerss || [];
	const testAnswersIsShared = testAnswerss.length === 1 && variationCount > 1;

	if (testAnswerss.length > 0) {
		if (testAnswersIsShared) {
			const validationRules = convertTestAnswers(testAnswerss[0], warnings);
			if (validationRules && validationRules.length > 0) {
				shared.validationRules = validationRules;
			}
		} else {
			for (let i = 0; i < variationCount; i++) {
				const testAnswers = testAnswerss[i] || testAnswerss[0];
				const validationRules = convertTestAnswers(testAnswers, warnings);
				if (validationRules && validationRules.length > 0) {
					perVariation[i].validationRules = validationRules;
				}
			}
		}
	}

	return { shared, perVariation };
}

/**
 * Check if shared object has any meaningful content
 */
function hasSharedContent(shared: SharedVariationDefaults): boolean {
	return !!(
		shared.statement ||
		(shared.variables && shared.variables.length > 0) ||
		shared.correctChoiceIndex !== undefined ||
		shared.correction ||
		(shared.choices && shared.choices.length > 0) ||
		(shared.validationRules && shared.validationRules.length > 0) ||
		(shared.answerFormats && Object.keys(shared.answerFormats).length > 0) ||
		shared.blankDefaults ||
		shared.requiredForm
	);
}

