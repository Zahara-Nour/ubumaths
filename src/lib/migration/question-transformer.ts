/**
 * Transform a single old question to new format
 *
 * @param oldQuestion - The old TinyMath question object
 * @param questionIndex - Index of this question in the batch
 * @param options - Transformation options
 * @param options.skipImages - If true, skip questions with images
 * @param options.skipCustomValidation - If true, skip questions with testAnswers
 * @param options.imageUrlMapping - Optional mapping from old image paths to new Supabase URLs
 * @returns Transformation result with template, warnings, errors, and stats
 */
export function transformQuestion(
	oldQuestion: QuestionBase,
	questionIndex: number,
	options?: {
		skipImages?: boolean;
		skipCustomValidation?: boolean;
		imageUrlMapping?: ImageUrlMapping;
	}
): TransformResult {
	const warnings: string[] = [];
	const errors: string[] = [];
	const stats: TransformStats = {
		variations: 0,
		variables: 0,
		syntaxConversions: 0,
		optionsMapped: 0,
		displayOptionsMapped: 0,
		correctionConversions: 0,
		detectedType: '',
		hasImages: false,
		hasCustomValidation: false,
		imagesConverted: 0,
		imagesMissing: 0,
		asciiMathConverted: 0
	};

	try {
		// Check for unsupported features
		if (hasImages(oldQuestion)) {
			stats.hasImages = true;
			if (options?.skipImages && !options?.imageUrlMapping) {
				// Only skip if no image mapping provided
				errors.push('Question contains images - skipping for Phase 1');
				return { success: false, errors, stats };
			} else if (!options?.imageUrlMapping) {
				warnings.push('Question contains images - will need manual review');
			}
			// If imageUrlMapping is provided, proceed with conversion
		}

		if (hasTestAnswers(oldQuestion)) {
			stats.hasCustomValidation = true;
			if (options?.skipCustomValidation) {
				errors.push('Question has custom validation - skipping for Phase 1');
				return { success: false, errors, stats };
			} else {
				warnings.push(
					'Question has custom validation (testAnswers) - needs Phase 4 implementation'
				);
			}
		}

		// Detect migration mode + legacy type for stats
		const migrationMode = detectMigrationMode(oldQuestion);
		stats.detectedType = detectQuestionType(oldQuestion);

		// Create variations with shared field detection
		const sharedResult = createVariationsWithShared(
			oldQuestion,
			migrationMode,
			options?.imageUrlMapping,
			warnings,
			stats
		);
		const variations = sharedResult.variations;
		let shared = sharedResult.shared;

		if (variations.length === 0) {
			errors.push('No variations could be created');
			return { success: false, errors, warnings, stats };
		}

		// Convert options
		const {
			options: convertedOptions,
			defaultDisplayOptions,
			requiredForm
		} = convertOptions(oldQuestion.options, warnings, oldQuestion.formats);
		if (convertedOptions) {
			stats.optionsMapped = Object.keys(convertedOptions).length;
		}
		if (defaultDisplayOptions) {
			stats.displayOptionsMapped = Object.keys(defaultDisplayOptions).length;

			// Attach displayOptions to expression variables (not template-level defaultDisplayOptions)
			// In the old system, display options like exp-no-spaces, exp-remove-unecessary-brackets,
			// shuffle-terms, remove-null-terms all apply to the expression field,
			// which is now a variable named "expressionN".
			for (const variation of variations) {
				if (variation.variables) {
					for (const variable of variation.variables) {
						if (variable.name.startsWith('expression')) {
							variable.displayOptions = { ...defaultDisplayOptions };
						}
					}
				}
			}
			// Also check shared variables
			if (shared?.variables) {
				for (const variable of shared.variables) {
					if (variable.name.startsWith('expression')) {
						variable.displayOptions = { ...defaultDisplayOptions };
					}
				}
			}
		}

		// Apply requiredForm to shared (applies to all variations)
		if (requiredForm) {
			if (!shared) {
				shared = {};
			}
			shared.requiredForm = requiredForm;
		}

		// Assign category
		const category = assignCategory(oldQuestion);

		// Create template (without id/audit fields - will be auto-generated by database)
		// Apply fixMathDelimiters to title, description, and help text
		// NOTE: `type` is no longer stored — it's inferred from structure (choices present → MC)
		const template: Omit<QuestionTemplate, 'id' | 'created_at' | 'updated_at' | 'created_by'> = {
			title: fixMathDelimiters(oldQuestion.description),
			description: oldQuestion.subdescription
				? fixMathDelimiters(oldQuestion.subdescription)
				: undefined,
			shared, // Include shared defaults when fields are reused across variations
			variations,
			exerciseInstruction: oldQuestion.help ? fixMathDelimiters(oldQuestion.help) : undefined,
			options: convertedOptions,
			// displayOptions are attached to expression variables directly, not at template level
			grades: [mapGrade(oldQuestion.grade)],
			...category,
			status: 'draft', // Import as draft for review
			multipleAnswers: oldQuestion.multipleAnswers
		};

		// Add optional fields
		if (oldQuestion.defaultDelay > 0) {
			template.delay = oldQuestion.defaultDelay;
		}

		// Add precision for decimal questions (via shared blankDefaults)
		if (oldQuestion['result-type'] === 'decimal') {
			if (!template.shared) template.shared = {};
			template.shared.blankDefaults = {
				...template.shared.blankDefaults,
				precision: { type: 'decimal', digits: 2 }
			};
			warnings.push('Decimal precision set to 2 places by default - verify if correct');
		}

		return {
			success: true,
			template,
			warnings: warnings.length > 0 ? warnings : undefined,
			stats
		};
	} catch (error) {
		errors.push(`Unexpected error: ${error instanceof Error ? error.message : String(error)}`);
		return {
			success: false,
			errors,
			warnings: warnings.length > 0 ? warnings : undefined,
			stats
		};
	}
}

