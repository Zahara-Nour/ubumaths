/**
 * Create variations from old question structure with shared field detection
 *
 * @param oldQuestion - The old question object
 * @param questionType - Detected question type
 * @param imageMapping - Optional mapping from old image paths to new URLs
 * @param warnings - Array to collect warnings
 * @param stats - Stats object to track conversions
 * @returns Object containing variations and optionally shared defaults
 */
function createVariationsWithShared(
	oldQuestion: QuestionBase,
	migrationMode: MigrationMode,
	imageMapping: ImageUrlMapping | undefined,
	warnings: string[],
	stats: TransformStats
): { variations: QuestionVariation[]; shared?: SharedVariationDefaults } {
	const variationCount = getVariationCount(oldQuestion);
	stats.variations = variationCount;

	// Detect shared fields
	const { shared, perVariation } = detectSharedFields(
		oldQuestion,
		variationCount,
		migrationMode,
		imageMapping,
		warnings,
		stats
	);

	// Handle blanks based on migration mode
	const expressions = oldQuestion.expressions || [];
	const solutionss = oldQuestion.solutionss || [];
	const oldAnswerFormats = oldQuestion.answerFormats || [];

	if (migrationMode === 'fill_in') {
		// Fill-in: expressions with ? → blanks from expression
		for (let i = 0; i < variationCount; i++) {
			const expression = expressions[i] || expressions[0];
			const solutions = solutionss[i] || solutionss[0];
			if (expression) {
				const blanks = extractBlanks(expression, solutions, warnings);
				if (blanks && blanks.length > 0) {
					perVariation[i].blanks = blanks;
				}
			}
		}
	} else if (migrationMode === 'result_rewrite') {
		// Result/rewrite: blanks from solutionss, answerFormats extracted
		const hasSharedAnswerFormat = oldAnswerFormats.length === 1 && variationCount > 1;
		const sharedAnswerFormat = oldAnswerFormats[0]; // undefined when no formats

		// Extract answerFormats to shared when single format for multiple variations
		if (hasSharedAnswerFormat && sharedAnswerFormat) {
			const exprVarName = expressions.length <= 1 ? 'expression1' : undefined;
			if (exprVarName) {
				shared.answerFormats = { [exprVarName]: sharedAnswerFormat };
			}
		}

		for (let i = 0; i < variationCount; i++) {
			const solutions = solutionss[i] || solutionss[0];
			const answerFormat = oldAnswerFormats[i] || oldAnswerFormats[0];
			const exprVarName = expressions.length <= 1 ? 'expression1' : `expression${i + 1}`;

			const blanks = extractBlanksFromSolutions(solutions, answerFormat, exprVarName, warnings);
			if (blanks.length > 0) {
				perVariation[i].blanks = blanks;
			}

			// Per-variation answerFormats (when not shared)
			if (answerFormat && !hasSharedAnswerFormat) {
				perVariation[i].answerFormats = { [exprVarName]: answerFormat };
			}
		}
	} else if (migrationMode === 'answer_field') {
		// AnswerField: blanks from solutionss, count from $$...$$ in answerField
		const answerFields = oldQuestion.answerFields || [];

		for (let i = 0; i < variationCount; i++) {
			const solutions = solutionss[i] || solutionss[0];
			const af = answerFields[i] || answerFields[0];

			// Count blanks from $$...$$ markers in answerField
			const blankCount = af ? (af.match(/\$\$\.\.\.\$\$/g) || []).length : 0;

			if (solutions && solutions.length > 0 && blankCount > 0) {
				const blanks = extractBlanksFromSolutions(
					solutions,
					undefined, // No answerFormat for answerFields
					undefined, // No expression variable
					warnings,
					blankCount
				);
				if (blanks.length > 0) {
					perVariation[i].blanks = blanks;
				}
			}
		}
	}

	// Build variations array from per-variation data
	const variations: QuestionVariation[] = perVariation.map((pv, index) => {
		// Start with required fields - use shared fallback or throw error
		const statement = pv.statement || shared.statement;
		const correctChoiceIndex = pv.correctChoiceIndex ?? shared.correctChoiceIndex;

		if (!statement) {
			warnings.push(`Variation ${index}: missing statement`);
		}
		// Only warn about missing correctChoiceIndex for multiple_choice
		if (correctChoiceIndex === undefined && migrationMode === 'multiple_choice') {
			warnings.push(`Variation ${index}: missing correctChoiceIndex`);
		}

		const variation: QuestionVariation = {
			statement: statement || templateMarkdown('')
		};

		// correctChoiceIndex only for multiple_choice
		if (correctChoiceIndex !== undefined) {
			variation.correctChoiceIndex = correctChoiceIndex;
		}

		// Add optional fields only if they exist and are NOT shared
		if (pv.variables && pv.variables.length > 0) {
			variation.variables = pv.variables;
		}
		if (pv.correction) {
			variation.correction = pv.correction;
		}
		if (pv.choices && pv.choices.length > 0) {
			variation.choices = pv.choices;
		}
		if (pv.validationRules && pv.validationRules.length > 0) {
			variation.validationRules = pv.validationRules;
		}
		if (pv.blanks && pv.blanks.length > 0) {
			variation.blanks = pv.blanks;
		}
		if (pv.answerFormats && Object.keys(pv.answerFormats).length > 0) {
			variation.answerFormats = pv.answerFormats;
		}

		return variation;
	});

	// Return shared only if it has meaningful content
	return {
		variations,
		shared: hasSharedContent(shared) ? shared : undefined
	};
}

/**
 * Extract blank positions and answers from expression with ?
 */
function extractBlanks(
	expression: string,
	solutions: (string | number)[] | undefined,
	warnings: string[]
): QuestionVariation['blanks'] {
	const blanks: NonNullable<QuestionVariation['blanks']> = [];

	// Count ? marks in expression
	const questionMarks = (expression.match(/\?/g) || []).length;

	if (questionMarks === 0) {
		warnings.push('Fill-in-blanks detected but no ? marks found in expression');
		return undefined;
	}

	// Each ? corresponds to a solution
	for (let i = 0; i < questionMarks; i++) {
		const answer = solutions?.[i];
		if (answer !== undefined) {
			const conversionResult = convertTinyCASToNew(String(answer));
			blanks.push({
				position: i,
				expectedAnswer: conversionResult.converted || String(answer)
			});
		} else {
			warnings.push(`Missing solution for blank at position ${i}`);
			blanks.push({
				position: i,
				expectedAnswer: ''
			});
		}
	}

	return blanks.length > 0 ? blanks : undefined;
}

